 select category_name, count(prdouct__key) as total_products
 from gold.dim_product
 group by category_name
 order by 2 desc ;  -- total products by category 
  -- ----------------------------------------------- --
   Select category_name, round(avg(product_cost),0) as avg_prdouct_cost_per_category
 from gold.dim_product
