 -- ------------------------------------------------------------- -- 
  select d.category_name as category_name, sum(s.sls_sales) as total_revenue 
  from gold.fact_Sales s
left join gold.dim_product d
on s.prdouct__key = d.prdouct__key
group by 1
order by 2 desc; -- total revenue by each product 
 -- ------------------------------------------------------------------ --
 select  c.customer_key, c.first_name,c.last_name, sum(s.sls_sales) as total_revenue
 from  gold.fact_Sales s
 left join gold.dim_customers c
 on s.customer_key= c.customer_key
 group by 1,2,3
 order by 4  desc;   -- total revenue generated by each customer 
-- ----------------------------------------------------------- -- 
 select  c.country,  sum(sls_quantity) as total_quantities
 from  gold.fact_Sales s
 left join gold.dim_customers c
 on s.customer_key= c.customer_key
 group by 1
 order by 2  desc;  -- the distribution of sold items across countries 
 -- ----------------------------------------------------------------- --
 select d.product_name as product_name, sum(s.sls_sales) as total_revenue ,
  dense_rank() over( order by sum(s.sls_sales) desc ) as top_product
  from gold.fact_Sales s
left join gold.dim_product d
on s.prdouct__key = d.prdouct__key
group by 1
 --  top_product by total revenue 
limit 5 ;
-- -------------------------------------------------------------------- --
